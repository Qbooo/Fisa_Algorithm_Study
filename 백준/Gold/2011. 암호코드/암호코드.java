import java.io.*;
public class Main {
    public static void main(String[] args) throws IOException {
        /*
        25114

1111111111

1개 혹은 2개씩 잡아서 해석 가능 단 2개를 잡으려면 26이하의 숫자여야한다.

경우의 수를 구하는거기 때문에

어떤 알고리즘을 쓰면 좋을지 모르겠었는데 이 부분도 DP가 좋다고 한다
한자리씩 붙여 나갈때 마다 그 전의 경우의 수를 그대로 가저갈수도 있고 둘이 합쳐 26이하인 경우에는 2개를 합치는 경우도 있다.

25114
dp[1] 2      B
 
dp[2] 2, 5   B E  
        25   Y    

dp[3] 251
    1 혼자 묶는경우 -> BEA, YA -> 2가지
    51은 26보다 커서 안됨

dp[4] 2511
    1 혼자 묶는 경우 -> BEAA, YAA -> 2가지
    11 묶는 경우 -> BEK, YK -> 2가지
    -> 4가지

dp[5] 25114
    4 혼자 묶는 경우 -> 4가지 = dp[4]
    14 같이 묶는 경우 -> 2가지 = dp[3]

-> 총 6가지

고려해야 할 사항 1 26을 넘는수인지 아닌지
고려해야 할 사항 2 0의 존재

만약 20104였다면

0이 나오는 순간 앞 숫자랑 묶었을때 26보다 큰 수라면 바로 0을 출력
가장 첫 자리가 0이더라도 0을 출력


        */
        BufferedReader br = new BufferedReader(new InputStreamReader(System.in));
        String s = br.readLine();
        int n = s.length();
        
        long[] dp = new long[n + 1];
        
        // 빈 문자열의 경우의 수 = 1 (점화식이 자연스럽게 동작하기 위한 기저값)
        dp[0] = 1;
        // 첫 자리가 0이면 해석 불가 → 0, 아니면 1가지
        dp[1] = s.charAt(0) == '0' ? 0 : 1;
        
        for (int i = 2; i <= n; i++) {
            int one = s.charAt(i-1) - '0';             // 현재 자리 숫자 (1개로 읽기)
            int two = Integer.parseInt(s.substring(i-2, i)); // 이전+현재 자리 숫자 (2개 묶어 읽기)
            
            // [고려사항 2: 0의 존재]
            // one이 0이면 혼자 읽기 불가 (0은 알파벳 매핑 없음)
            // one이 0이 아닐때만 dp[i-1] (이전까지의 경우의 수)를 그대로 가져옴
            if (one != 0) {
                dp[i] += dp[i-1]; // "한자리씩 붙여나갈때 그 전의 경우의 수를 그대로 가져감"
            }
            
            // [고려사항 1: 26을 넘는 수인지]
            // [고려사항 2: 0의 존재] two >= 10 조건으로 01, 02 같은 경우 자동 제외
            // 두 자리가 10~26 사이일때만 묶어 읽기 가능 → dp[i-2] 추가
            if (two >= 10 && two <= 26) {
                dp[i] += dp[i-2]; // "둘이 합쳐 26이하인 경우에는 2개를 합치는 경우도 있다"
            }
            
            // 정답이 매우 클 수 있으므로 매 단계마다 나머지 처리
            dp[i] %= 1000000;
        }
        
        // 전체 문자열의 해석 가짓수 출력
        // dp[n]이 0이면 해석 불가능한 암호
        System.out.println(dp[n]);
    }
}